#include <iostream>
using namespace std;

int main()
{
    // Store the student's roll number using an integer
    int roll = 101;

    // Store the student's grade using a character
    char grade = 'A';

    // Store the fee amount using a floating-point value
    float fee = 12500.50;

    // Display the student's roll number
    cout << "Roll No: " << roll << endl;

    // Display the student's grade
    cout << "Grade: " << grade << endl;

    // Display the student's fee amount
    cout << "Fee: " << fee << endl;

    return 0;
}